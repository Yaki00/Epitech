export const DICTIONARIES = { fr, en };
export const LANGS = ['fr', 'en'];
const STORAGE_KEY = 'lyra.lang';

function initialLang() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* stockage indisponible : langue par défaut */
  }
  return 'fr';
}

let current = typeof window === 'undefined' ? 'fr' : initialLang();

/** Langue courante, pour le code hors composant (formatage des dates, libellés). */
export const getLang = () => current;
/** Change la langue courante sans passer par React (tests). */
export const setCurrentLang = (lang) => {
  current = LANGS.includes(lang) ? lang : 'fr';
};

/** Traduit une clé ; clé inconnue = la clé elle-même (visible, donc repérable). */
export function translate(lang, key, vars = {}) {
  const value = DICTIONARIES[lang]?.[key] ?? DICTIONARIES.fr[key];
  if (value === undefined) return key;
  if (typeof value === 'function') return value(vars);
  return value.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}

/** Traduction dans la langue courante (hors composant). */
export const t = (key, vars) => translate(current, key, vars);

const I18nContext = createContext({ lang: 'fr', setLang: () => {}, t: (k, v) => translate('fr', k, v) });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(current);
  const setLang = useCallback((next) => {
    setCurrentLang(next);
    setLangState(current);
    try {
      window.localStorage.setItem(STORAGE_KEY, current);
    } catch {
      /* stockage indisponible : la langue tient jusqu'au rechargement */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
